"""Rebuild pinned Dutch station artwork; requires Pillow 12.3.0.

Usage: .venv/bin/python scripts/generate-station-logos.py [--source-dir DIR]
Without a source directory, fetch the public HTTPS URLs recorded in the manifest.
Checksums must match before the checked-in asset header is replaced.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import urllib.request
from PIL import Image, ImageOps, __version__

root = Path(__file__).resolve().parents[1]
component = root / "esphome/components/online_image"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source-dir", type=Path)
args = parser.parse_args()
if __version__ != "12.3.0":
    raise SystemExit("Use Pillow 12.3.0 for reproducible JPEG bytes.")
stations = json.loads((component / "station_logos.json").read_text())
lines = ['#pragma once', '#include <cstddef>', '#include <cstdint>', '#include "station_artwork.h"',
         '#include "radionl_logo.h"', '', 'namespace esphome::online_image {',
         '// Generated by scripts/generate-station-logos.py; see station_logos.json.',
         '// Logos belong to their respective stations and identify those stations only.']
names = []
for station in stations:
    if args.source_dir:
        raw = (args.source_dir / (station['key'] + '.source')).read_bytes()
    else:
        with urllib.request.urlopen(station['url'], timeout=25) as response:
            raw = response.read(2 * 1024 * 1024 + 1)
    if hashlib.sha256(raw).hexdigest() != station['source_sha256']:
        raise SystemExit(f"Source changed: {station['name']}. Inspect it before updating the manifest.")
    image = ImageOps.exif_transpose(Image.open(io.BytesIO(raw))).convert('RGBA')
    image.thumbnail((272, 272), Image.Resampling.LANCZOS)
    # Square padding preserves wide NPO marks when the existing thumbnail cache
    # center-crops player/favorite artwork. Composite transparency onto white.
    canvas = Image.new('RGB', (272, 272), 'white')
    canvas.paste(image, ((272 - image.width) // 2, (272 - image.height) // 2), image.getchannel('A'))
    encoded = io.BytesIO()
    canvas.save(encoded, format='JPEG', quality=90, optimize=True, progressive=False)
    name = 'STATION_' + station['key'].upper().replace('-', '_') + '_LOGO'
    names.append(name)
    lines += ['', f"// {station['name']}, TuneIn {station['station_id']}; retrieved 2026-10-12.",
              '// ' + station['url'], '// Original SHA256: ' + station['source_sha256'],
              '// 272x272, white square padding, baseline JPEG, quality 90, optimized; Pillow 12.3.0.',
              f'inline constexpr uint8_t {name}[] = {{']
    data = encoded.getvalue()
    for start in range(0, len(data), 16):
        lines.append('  ' + ', '.join(f'0x{byte:02x}' for byte in data[start:start + 16]) + ',')
    lines.append('};')
    print(f"{station['name']}: {len(data)} bytes")
lines += ['', 'struct StationLogo { const uint8_t *data; size_t size; };',
          '// Keep each asset paired with the corresponding metadata registry entry.',
          'inline constexpr StationLogo STATION_LOGOS[] = {']
for name in names:
    lines.append(f'  {{{name}, sizeof({name})}},')
lines += ['  {RADIONL_LOGO, sizeof(RADIONL_LOGO)},', '};',
          'static_assert(sizeof(STATION_LOGOS) / sizeof(STATION_LOGOS[0]) == energydeck_artwork::STATION_COUNT);']
# Compile-time identity checks make a registry reorder fail rather than show a wrong logo.
lines.insert(3, '#include <string_view>')
for i, station in enumerate(stations):
    lines.append(f'static_assert(std::string_view(energydeck_artwork::STATIONS[{i}].tunein_id) == "{station["station_id"]}");')
lines += [f'static_assert(std::string_view(energydeck_artwork::STATIONS[{len(stations)}].tunein_id) == "s106736");',
          '}  // namespace esphome::online_image', '']
(component / "station_logos.h").write_text('\n'.join(line for line in lines))
